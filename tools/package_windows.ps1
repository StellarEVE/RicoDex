$portableReadme = @"
RicoDex portable Windows build

1. Extract this ZIP to a writable folder.
2. If Windows reports a missing Microsoft Visual C++ runtime, run
   vc_redist.x64.exe once, then restart RicoDex.
3. Run Launch-RicoDex.cmd, or open RicoDex\ricodex-app.exe directly.

The package is an experimental CI validation build, not an approved
public redistribution release. See RicoDex\DISTRIBUTION-STATUS.txt.
"@
$portableReadme | Set-Content -Path (Join-Path $appStage "README.txt") -Encoding utf8

$launcher = @'
@echo off
setlocal
set "ROOT=%~dp0"
if not exist "%WINDIR%\System32\vcruntime140.dll" (
  echo Installing Microsoft Visual C++ Redistributable...
  "%ROOT%vc_redist.x64.exe" /install /quiet /norestart
  if errorlevel 1 (
    echo The Visual C++ Redistributable installer reported an error.
    pause
    exit /b 1
  )
)
start "" "%ROOT%RicoDex\ricodex-app.exe"
'@
$launcher | Set-Content -Path (Join-Path $appStage "Launch-RicoDex.cmd") -Encoding ascii

$vcRedist = Join-Path $appStage "vc_redist.x64.exe"
if (-not (Test-Path $vcRedist -PathType Leaf)) {
    throw "Microsoft Visual C++ Redistributable was not downloaded to $vcRedist"
}

Write-Host "Staged RicoDex portable package at $appStage"
Write-Host "FFmpeg runtime DLLs copied: $($ffmpegDlls.Count)"
