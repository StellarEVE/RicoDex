param(
    [Parameter(Mandatory = $true)]
    [string]$FfmpegRoot,

    [string]$OutputRoot = "dist\portable",

    [string]$FfmpegArchiveUrl = "https://github.com/BtbN/FFmpeg-Builds/releases/download/latest/ffmpeg-n8.1-latest-win64-lgpl-shared-8.1.zip",

    [string]$FfmpegArchiveSha256 = ""
)

$ErrorActionPreference = "Stop"

$repoRoot = Resolve-Path (Join-Path $PSScriptRoot "..")
Set-Location $repoRoot

$ffmpegRootPath = (Resolve-Path $FfmpegRoot).Path
$ffmpegBin = Join-Path $ffmpegRootPath "bin"
$appStage = Join-Path $repoRoot $OutputRoot
$licenseStage = Join-Path $appStage "RicoDex\licenses"

if (-not (Test-Path $ffmpegBin -PathType Container)) {
    throw "FFmpeg bin directory was not found: $ffmpegBin"
}

$requiredExecutables = @(
    "target\release\ricodex-app.exe",
    "target\release\ricodex-cli.exe"
)
foreach ($relativePath in $requiredExecutables) {
    if (-not (Test-Path (Join-Path $repoRoot $relativePath) -PathType Leaf)) {
        throw "Required release executable is missing: $relativePath"
    }
}

$ffmpegDlls = @(Get-ChildItem -Path $ffmpegBin -Filter "*.dll" -File)
if ($ffmpegDlls.Count -eq 0) {
    throw "No FFmpeg runtime DLLs were found in $ffmpegBin"
}

foreach ($pattern in @("avcodec*.dll", "avformat*.dll", "avutil*.dll")) {
    if (-not ($ffmpegDlls | Where-Object { $_.Name -like $pattern })) {
        throw "Required FFmpeg runtime library matching '$pattern' is missing."
    }
}

if (Test-Path $appStage) {
    Remove-Item $appStage -Recurse -Force
}

New-Item -ItemType Directory -Path $licenseStage -Force | Out-Null

Copy-Item (Join-Path $repoRoot "target\release\ricodex-app.exe") (Join-Path $appStage "RicoDex\ricodex-app.exe")
Copy-Item (Join-Path $repoRoot "target\release\ricodex-cli.exe") (Join-Path $appStage "RicoDex\ricodex-cli.exe")

# The shared FFmpeg package builds the libav* DLL family and any DLL
# dependencies it needs into this directory. Ship the whole DLL set so
# runtime dependencies are not accidentally omitted.
foreach ($dll in $ffmpegDlls) {
    Copy-Item $dll.FullName (Join-Path $appStage "RicoDex\$($dll.Name)")
}

$licenseUrls = @{
    "FFmpeg-LICENSE.md" = "https://raw.githubusercontent.com/FFmpeg/FFmpeg/n8.1/LICENSE.md"
    "COPYING.LGPLv2.1" = "https://raw.githubusercontent.com/FFmpeg/FFmpeg/n8.1/COPYING.LGPLv2.1"
}
foreach ($entry in $licenseUrls.GetEnumerator()) {
    $destination = Join-Path $licenseStage $entry.Key
    Invoke-WebRequest -Uri $entry.Value -OutFile $destination
    if (-not (Test-Path $destination -PathType Leaf) -or (Get-Item $destination).Length -lt 1000) {
        throw "Failed to retrieve the FFmpeg license file: $($entry.Key)"
    }
}

$ffmpegExe = Join-Path $ffmpegBin "ffmpeg.exe"
if (Test-Path $ffmpegExe -PathType Leaf) {
    & $ffmpegExe -version 2>&1 | Out-File -FilePath (Join-Path $licenseStage "FFmpeg-build-info.txt") -Encoding utf8
}

if ($FfmpegArchiveSha256) {
    @(
        "FFmpeg archive SHA-256: $FfmpegArchiveSha256"
        "FFmpeg archive URL: $FfmpegArchiveUrl"
    ) | Set-Content -Path (Join-Path $licenseStage "FFmpeg-archive-provenance.txt") -Encoding utf8
}

